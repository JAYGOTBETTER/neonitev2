#!/usr/bin/env python3
"""Preflight the design sheets and generate src/generated/sheets.h from them.

  python3 tools/sheets.py preflight   # list unfilled cells, broken refs, unverified cells
  python3 tools/sheets.py generate    # preflight, then write the C++ header

Preflight fails (exit 1) on unfilled cells or references that do not resolve.
Unverified cells are listed but do not block a build: they block publishing.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SHEETS = ROOT / "sheets"
OUT = ROOT / "src" / "generated" / "sheets.h"

PAD_BUTTONS = {
    "DPAD_UP": 0x0001, "DPAD_DOWN": 0x0002, "DPAD_LEFT": 0x0004, "DPAD_RIGHT": 0x0008,
    "START": 0x0010, "BACK": 0x0020, "LEFT_THUMB": 0x0040, "RIGHT_THUMB": 0x0080,
    "LEFT_SHOULDER": 0x0100, "RIGHT_SHOULDER": 0x0200, "A": 0x1000, "B": 0x2000,
    "X": 0x4000, "Y": 0x8000,
}
HOOK_KINDS = {"callsite", "function", "riprel"}


def load():
    return {p.stem: json.loads(p.read_text()) for p in sorted(SHEETS.glob("*.json"))}


def index(sheets):
    return {name: {r["id"]: r for r in s["rows"]} for name, s in sheets.items()}


def resolve(ref, idx):
    """'=sheet.row.column' -> value, or raise KeyError."""
    sheet, row, col = ref[1:].split(".")
    return idx[sheet][row][col]


def preflight(sheets):
    errors, unverified = [], []
    idx = index(sheets)
    for name, s in sheets.items():
        for row in s["rows"]:
            rid = row.get("id", "?")
            verify = row.get("_verify", {})
            for col in s["columns"]:
                cell = f"{name}.{rid}.{col}"
                if col not in row or row[col] in ("", None, []):
                    errors.append(f"unfilled: {cell}")
                    continue
                val = row[col]
                if isinstance(val, str) and val.startswith("="):
                    try:
                        resolve(val, idx)
                    except (KeyError, ValueError):
                        errors.append(f"broken ref: {cell} -> {val}")
                if col not in verify:
                    errors.append(f"no verification note: {cell}")
                elif str(verify[col]).startswith("UNVERIFIED"):
                    unverified.append(f"{cell}: {verify[col]}")
            for extra, note in verify.items():
                if extra not in s["columns"] and str(note).startswith("UNVERIFIED"):
                    unverified.append(f"{name}.{rid}.{extra}: {note}")

    # Cross-sheet references and value domains.
    for row in sheets["characters"]["rows"]:
        for m in row["morphs"]:
            if m not in idx["morphs"]:
                errors.append(f"broken ref: characters.{row['id']}.morphs -> {m}")
    for row in sheets["morphs"]["rows"]:
        if row["padButton"] not in PAD_BUTTONS:
            errors.append(f"bad value: morphs.{row['id']}.padButton = {row['padButton']}")
        if not (len(row["key"]) == 1 and row["key"].isalnum()):
            errors.append(f"bad value: morphs.{row['id']}.key = {row['key']} (one letter or digit)")
    for row in sheets["hooks"]["rows"]:
        if row["kind"] not in HOOK_KINDS:
            errors.append(f"bad value: hooks.{row['id']}.kind = {row['kind']}")
        if row["kind"] == "callsite" and not row["pattern"].startswith("E8"):
            errors.append(f"bad value: hooks.{row['id']} callsite pattern must start at an E8 call")
    return errors, unverified


def c_str(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def generate(sheets):
    idx = index(sheets)
    hooks = sheets["hooks"]["rows"]
    lines = [
        "// GENERATED by tools/sheets.py from sheets/*.json. Do not edit; change the sheet.",
        "#pragma once",
        "#include <cstdint>",
        "",
        "namespace bb {",
        "",
        "enum HookId {",
    ]
    lines += [f"    HOOK_{h['id']}," for h in hooks]
    lines += ["    HOOK_COUNT", "};", ""]
    lines += [
        "enum HookKind { KIND_CALLSITE, KIND_FUNCTION, KIND_RIPREL };",
        "",
        "struct HookRow { const char* id; HookKind kind; const char* pattern; int offset; const char* purpose; };",
        "",
        "inline constexpr HookRow kHooks[HOOK_COUNT] = {",
    ]
    for h in hooks:
        kind = {"callsite": "KIND_CALLSITE", "function": "KIND_FUNCTION", "riprel": "KIND_RIPREL"}[h["kind"]]
        lines.append(f"    {{ {c_str(h['id'])}, {kind}, {c_str(h['pattern'])}, {h['offset']}, {c_str(h['purpose'])} }},")
    lines += ["};", ""]

    morphs = sheets["morphs"]["rows"]
    lines += [
        "struct MorphRow { const char* id; const char* displayName; const char* assistCharacter;",
        "                  uint16_t padButton; char key; float hiddenScale; uint32_t durationMs; uint32_t cooldownMs; };",
        "",
        f"inline constexpr int kMorphCount = {len(morphs)};",
        "inline constexpr MorphRow kMorphs[kMorphCount] = {",
    ]
    for m in morphs:
        lines.append(
            f"    {{ {c_str(m['id'])}, {c_str(m['displayName'])}, {c_str(m['assistCharacter'])}, "
            f"0x{PAD_BUTTONS[m['padButton']]:04X} /* {m['padButton']} */, '{m['key'].upper()}', "
            f"{float(m['hiddenScale'])}f, {int(m['durationMs'])}u, {int(m['cooldownMs'])}u }},")
    lines += ["};", ""]

    chars = sheets["characters"]["rows"]
    morph_ids = [m["id"] for m in morphs]
    lines += [
        "struct CharacterRow { const char* id; const char* displayName; const char* baseCharacterMatch;",
        "                      const char* lookModifier; int morph; bool anySlot; };",
        "",
        f"inline constexpr int kCharacterCount = {len(chars)};",
        "inline constexpr CharacterRow kCharacters[kCharacterCount] = {",
    ]
    for c in chars:
        # v0.1: one morph per fighter (the first listed).
        lines.append(
            f"    {{ {c_str(c['id'])}, {c_str(c['displayName'])}, {c_str(c['baseCharacterMatch'])}, "
            f"{c_str(c['lookModifier'])}, {morph_ids.index(c['morphs'][0])} /* {c['morphs'][0]} */, "
            f"{'true' if c['appliesTo'] == 'any_slot' else 'false'} }},")
    lines += ["};", ""]

    cfg = sheets["config"]["rows"]
    lines += [
        "struct ConfigRow { const char* section; const char* key; const char* defaultValue; };",
        "",
        f"inline constexpr int kConfigCount = {len(cfg)};",
        "inline constexpr ConfigRow kConfig[kConfigCount] = {",
    ]
    for r in cfg:
        val = r["default"]
        if isinstance(val, str) and val.startswith("="):
            val = resolve(val, idx)
        lines.append(f"    {{ {c_str(r['section'])}, {c_str(r['id'])}, {c_str(val)} }},")
    lines += ["};", "", "} // namespace bb", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))

    ini = []
    section = None
    for r in cfg:
        if r["section"] != section:
            section = r["section"]
            ini.append(f"{'' if not ini else chr(10)}[{section}]")
        val = r["default"]
        if isinstance(val, str) and val.startswith("="):
            val = resolve(val, idx)
        ini.append(f"{r['id']}={val}")
    (ROOT / "src" / "generated" / "BeastBoy.ini").write_text("\n".join(ini) + "\n")


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else "preflight"
    sheets = load()
    errors, unverified = preflight(sheets)
    print(f"preflight: {sum(len(s['rows']) for s in sheets.values())} rows in {len(sheets)} sheets")
    for e in errors:
        print("  ERROR  ", e)
    for u in unverified:
        print("  TODO   ", u)
    print(f"preflight: {len(errors)} errors, {len(unverified)} cells awaiting in-game verification")
    if errors:
        sys.exit(1)
    if cmd == "generate":
        generate(sheets)
        print(f"generated {OUT.relative_to(ROOT)} and src/generated/BeastBoy.ini")


if __name__ == "__main__":
    main()
